"""Measure compressed verified DEV attempts and count necessary copies explicitly."""
from pathlib import Path
import collections
import gzip
import hashlib
import io
import json
import tarfile

ROOT=Path(__file__).resolve().parents[4]
RUN=Path(__file__).resolve().parent
prior=json.loads((RUN/'storage-forecast.json').read_text(encoding='utf-8'))
manifest=json.loads((ROOT/'results/T-054/manifest-chuan-bi-main-006.json').read_text(encoding='utf-8'))['outputs']
class Counter(io.RawIOBase):
    def __init__(self):self.n=0
    def writable(self):return True
    def write(self,b):self.n+=len(b);return len(b)

observed={}
max_result=0
for group,rows in prior['observed_groups'].items():
    measured=[]
    for row in rows:
        sink=Counter()
        with gzip.GzipFile(fileobj=sink,mode='wb',compresslevel=6,mtime=0) as gz:
            with tarfile.open(fileobj=gz,mode='w|') as tar:
                for rel,v in sorted(manifest.items()):
                    if not rel.startswith(row['attempt']):continue
                    data=(ROOT/rel).read_bytes()
                    assert len(data)==v['bytes'] and hashlib.sha256(data).hexdigest()==v['sha256'],rel
                    item=tarfile.TarInfo(rel[len(row['attempt']):]);item.size=len(data);item.mtime=0
                    item.uid=item.gid=0;item.uname=item.gname=''
                    tar.addfile(item,io.BytesIO(data))
                    if rel.endswith('/result.json') and group.endswith('|M1'):
                        max_result=max(max_result,len(data))
        measured.append(dict(row,tar_gzip_bytes=sink.n))
    observed[group]=measured

by_host={}
for host,old in prior['forecasts'].items():
    raw=compressed=0;terms=[];largest=0
    for term in old['terms']:
        key=term['reference_group'];rows=observed[key]
        amount=max(x['bytes']for x in rows);gz=max(x['tar_gzip_bytes']for x in rows)
        raw+=term['jobs']*amount;compressed+=term['jobs']*gz;largest=max(largest,amount)
        terms.append({'group':term['group'],'jobs':term['jobs'],'reference_group':key,
                      'raw_max_per_attempt':amount,'compressed_max_per_attempt':gz,
                      'reference_is_fallback':term['fallback']})
    by_host[host]={'single_copy_empirical_bytes':raw,'compressed_empirical_bytes':compressed,
                   'largest_observed_attempt_bytes':largest,'terms':terms}

base=sum(v['single_copy_empirical_bytes']for v in by_host.values())
cloud_gzip=sum(by_host[h]['compressed_empirical_bytes']for h in ('ec2_1','ec2_2'))
# Retain the original 4x variation margin. Remove whole-cohort duplicates that
# are neither generated by the runner nor required for reporting.
native_plan=4*base
archives_plan=4*cloud_gzip
concurrent_temp=4*2*max(v['largest_observed_attempt_bytes']for v in by_host.values())
seal_plan=4*94*max_result
report_allowance=512*1024**2
headroom=2*1024**3
new_plan=native_plan+archives_plan+concurrent_temp+seal_plan+report_allowance+headroom
result={'schema':'T054-STORAGE-COPY-ACCOUNTING-011','status':'EMPIRICAL_PLANNING_NOT_GUARANTEED_BOUND',
        'measured_attempts':sum(map(len,observed.values())),'measured':observed,'by_host':by_host,
        'single_copy_empirical_bytes':base,'old_stacked_planning_bytes':prior['receive_all_hosts_plus_report_copy_bytes'],
        'corrected_components':{'native_once_local_or_received_4x':native_plan,
                                'retained_cloud_archives_4x':archives_plan,
                                'two_active_attempt_temp_4x':concurrent_temp,
                                'M1_seal_all94_4x':seal_plan,
                                'report_and_metadata_allowance':report_allowance,'operational_headroom':headroom},
        'corrected_planning_bytes':new_plan,
        'reason_removed':['No automatic whole-cohort retries; unknown failures stop and report',
                          'Reporting computes tables and selected M1 seals, not a second full clone of every attempt',
                          'Partial writes are concurrent attempt overhead, not a full duplicate of every completed job'],
        'kept':['all actual attempts, including failed ones','raw original results and receipt lineage','one received copy per cloud artifact plus its compressed transfer archive'],
        'not_required':['full extra retry allocation for every job before a retry is authorized','full extra report clone of the entire cohort'],
        'limits':['case complexity may exceed DEV; factor4 is a scenario, not a proven output bound',
                  'future approved retries/new cases require revisiting forecast','no cleanup/deletion or archive-only evaluator assumed'],
        'C_path_created':False,'new_methods_run':False}
(RUN/'storage-copy-accounting.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'single_copy_GiB':round(base/1024**3,3),'old_stacked_GiB':round(prior['receive_all_hosts_plus_report_copy_bytes']/1024**3,3),
                  'components_GiB':{k:round(v/1024**3,3)for k,v in result['corrected_components'].items()},
                  'corrected_total_GiB':round(new_plan/1024**3,3),'measured_attempts':result['measured_attempts']}))
